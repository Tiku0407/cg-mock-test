def series_of(no):
    """कुल सेट-क्रमांक (जैसे 32 या 1001) से सीरीज़ का नाम।"""
    return 'vyapam' if no > 1000 else 'cspdcl'


def arg_series(argv):
    """--series NAME (डिफ़ॉल्ट cspdcl) निकालकर बाकी तर्क लौटाता है।"""
    argv = list(argv); name = 'cspdcl'
    if '--series' in argv:
        i = argv.index('--series'); name = argv[i + 1]; del argv[i:i + 2]
    assert name in SERIES, f'अज्ञात सीरीज़: {name}'
    return name, argv
